-- Aplicar primero en una rama de desarrollo de Neon con conexión directa.
-- Complementa el esquema existente; no crea las tablas originales de la aplicación.
BEGIN;
ALTER TABLE productos ADD COLUMN IF NOT EXISTS version bigint;
UPDATE productos SET version = 0 WHERE version IS NULL;
ALTER TABLE productos ALTER COLUMN version SET DEFAULT 0;
ALTER TABLE insumos ADD COLUMN IF NOT EXISTS version bigint;
UPDATE insumos SET version = 0 WHERE version IS NULL;
ALTER TABLE insumos ALTER COLUMN version SET DEFAULT 0;
ALTER TABLE pedidos ADD COLUMN IF NOT EXISTS clave_compra varchar(36);
CREATE UNIQUE INDEX IF NOT EXISTS uq_pedidos_usuario_clave ON pedidos(usuario_id, clave_compra);
CREATE INDEX IF NOT EXISTS idx_pedidos_usuario_fecha ON pedidos(usuario_id, fecha);
CREATE INDEX IF NOT EXISTS idx_pedidos_fecha ON pedidos(fecha);
CREATE INDEX IF NOT EXISTS idx_detalle_pedidos_pedido ON detalle_pedidos(pedido_id);
CREATE TABLE IF NOT EXISTS receta_insumos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id integer NOT NULL REFERENCES productos(id),
    insumo_id integer NOT NULL REFERENCES insumos(id),
    cantidad numeric(19,6) NOT NULL CHECK (cantidad > 0),
    UNIQUE(producto_id, insumo_id)
);
CREATE INDEX IF NOT EXISTS idx_receta_insumo ON receta_insumos(insumo_id);
CREATE TABLE IF NOT EXISTS boletas_pendientes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id integer NOT NULL UNIQUE,
    destinatario varchar(255) NOT NULL,
    html text NOT NULL,
    proximo_intento timestamp with time zone NOT NULL,
    intentos integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_boletas_pendientes_fecha ON boletas_pendientes(proximo_intento);
COMMIT;
